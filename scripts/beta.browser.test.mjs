// Integrated shell checks with the offline server. No model calls or learner records.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createDemoServer } from './demo-server.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const server = createDemoServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const output = path.resolve('data/beta-review'); fs.mkdirSync(output, { recursive: true });
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 }, colorScheme: 'light' });
  const errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.method() === 'POST') requests.push({ url: request.url(), data: request.postDataJSON() }); });
  await page.route('**/*', route => route.request().url().startsWith(origin) ? route.continue() : route.abort());
  await page.goto(origin);
  await page.locator('#learnWelcome').waitFor();
  await page.locator('#input').fill('Keep my unsent reasoning.');
  await page.locator('#aboutMeLink').click();
  await page.getByText('Let’s build your learning picture', { exact: true }).waitFor();
  assert.equal(await page.locator('#chatMain').isVisible(), false);
  assert.equal(await page.locator('#aboutMeLink').getAttribute('aria-current'), 'page');
  assert.equal(requests.length, 0, 'viewing a profile does not write learner evidence');
  assert.ok(await page.locator('.beta-section-toolbar').evaluate(el => el.getBoundingClientRect().top >= 0), 'profile navigation remains visible');
  await page.screenshot({ path: path.join(output, 'about-me.png') });
  await page.locator('#betaBackToChat').click();
  await page.locator('#input').waitFor();
  assert.equal(await page.locator('#input').inputValue(), 'Keep my unsent reasoning.');
  await page.locator('#selfCheckLink').click();
  await page.getByRole('button', { name: 'Separate entropy transfer and generation', exact: false }).click();
  await page.screenshot({ path: path.join(output, 'self-check.png') });
  await page.getByRole('button', { name: 'Start this self-check', exact: true }).click();
  await page.locator('#selfCheckSession').waitFor();
  await page.locator('#thread').getByText(/Must the outlet specific entropy equal/).waitFor();
  const conversation = new URL(page.url()).hash;
  assert.match(conversation, /^#\/c\/demo-/);
  await page.locator('#input').fill('My answer is still being written.');
  await page.locator('#checkWorkBtn').click();
  await page.getByRole('button', { name: 'Give me a hint', exact: true }).click();
  await page.getByText('Practicing with support', { exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector('#sendBtn').classList.contains('stop'));
  assert.equal(await page.locator('#input').inputValue(), 'My answer is still being written.');
  const hint = requests.find(request => request.data.selfCheckAction === 'hint');
  assert.ok(hint, 'help uses an explicit server-validated action');
  assert.deepEqual(hint.data.attachments, []);
  assert.equal(hint.data.checkWork, false, 'a hint control is not submitted as written work');
  await page.locator('#aboutMeLink').click();
  await page.getByText('Let’s build your learning picture', { exact: true }).waitFor();
  await page.locator('#betaBackToChat').click();
  await page.locator('#selfCheckSession').waitFor();
  assert.equal(new URL(page.url()).hash, conversation);
  assert.equal(await page.locator('#input').inputValue(), 'My answer is still being written.');
  await page.getByRole('button', { name: 'Finish self-check', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#selfCheckSession').hidden && !document.querySelector('#sendBtn').classList.contains('stop'));
  await page.locator('#learnLink').click();
  await page.locator('#learnPanel').waitFor();
  assert.equal(await page.locator('[data-lesson]').count(), 8);
  assert.match(await page.locator('#learnProgressText').textContent(), /of 8/);
  const beforeTour = requests.length;
  await page.locator('[data-lesson="6"]').click();
  await page.locator('#learnTour[open]').waitFor();
  await page.keyboard.press('Escape');
  assert.equal(requests.length, beforeTour, 'touring new features does not submit a practice attempt');
  await page.locator('#learnReturn').click();
  await page.locator('#newChatBtn').click();
  assert.equal(await page.locator('#selfCheckSession').isVisible(), false);
  console.log('ok integrated profile/practice/tutorial routes, conversation preservation, explicit assistance and no fabricated preview evidence');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(origin + '/#/about-me');
  await page.getByText('Let’s build your learning picture', { exact: true }).waitFor();
  await page.locator('#betaSidebarButton').click();
  await page.locator('#selfCheckLink').click();
  await page.getByRole('button', { name: 'Start this self-check', exact: true }).waitFor();
  assert.equal(await page.locator('#app').evaluate(el => el.classList.contains('mobile-open')), false);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'no mobile horizontal overflow');
  await page.screenshot({ path: path.join(output, 'self-check-mobile.png') });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: path.join(output, 'self-check-mobile-dark.png') });
  await page.locator('#betaBackToChat').click();
  await page.locator('#input').waitFor();
  assert.equal(await page.locator('#betaPanels').isVisible(), false);
  assert.deepEqual(errors, []);
  console.log('ok direct links, mobile navigation, dark appearance and browser runtime');
} finally {
  await browser?.close(); await new Promise(resolve => server.close(resolve));
}
