import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createDemoServer } from './demo-server.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const server = createDemoServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const output = path.resolve('data/ui-review'); fs.mkdirSync(output, { recursive: true });
const spec = JSON.parse(fs.readFileSync('public/studio-demo.json', 'utf8'));
for (let i=2;i<6;i++) {
  spec.steps.push({label:'Check assumption '+i,latex:'\\dot m_{in}=\\dot m_{out}',note:'Track what crosses the boundary. State the steady-state assumption and verify the units in each term. Check that the chosen control volume includes the complete turbine.'});
  spec.lesson.segments[2].cues.push({target:'step:'+i,at:(i-1)*.18});
}
const content = 'Let’s look at the system together.\n\n```kelvin-board\n' + JSON.stringify(spec) + '\n```\n\nThe drawing stays beside our conversation.';
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    const synth = new EventTarget(); synth.getVoices = () => [];
    synth.speak = utterance => { window.activeSpeech = utterance; setTimeout(() => utterance.onstart?.(), 0); };
    synth.cancel = () => { window.activeSpeech = null; };
    Object.defineProperty(window, 'speechSynthesis', { value: synth });
    Object.defineProperty(window, 'SpeechSynthesisUtterance', { value: class { constructor(text) { this.text = text; } } });
  });
  await page.route('**/*', route => route.request().url().startsWith(origin) ? route.continue() : route.abort());
  await page.route('**/api/conversations/long', route => route.fulfill({ json: { id: 'long', title: 'Turbine', style: 'office-hours', messages: [{ role: 'user', content: 'Help me identify the turbine boundary.' }, { role: 'assistant', content }] } }));
  await page.goto(origin);
  await page.locator('#learnWelcome').waitFor();
  await page.locator('#studioCompanion .kel-button').waitFor();
  const logo = await page.locator('.brand img').evaluate(el => ({ natural:el.naturalWidth/el.naturalHeight, shown:el.width/el.height, fit:getComputedStyle(el).objectFit }));
  assert.equal(logo.fit, 'contain'); assert.ok(Math.abs(logo.natural-logo.shown)<.01);
  await page.screenshot({ path:path.join(output,'studio-desktop.png') });
  assert.equal(await page.locator('#studioWorkspace').isVisible(),false,'workspace starts closed');
  await page.locator('#workspaceOpen').click();
  await page.locator('#workspaceDemo').click();
  await page.locator('#studioBoardContent .knarration').waitFor();
  assert.match(await page.locator('#workspaceStatus').textContent(), /Practice example/);
  assert.equal(await page.evaluate(() => !!window.activeSpeech), false, 'example never autoplays');
  await page.getByRole('button',{name:'Next step',exact:true}).click();
  await page.getByRole('button',{name:'Next step',exact:true}).click();
  await page.getByRole('button',{name:'Next step',exact:true}).click();
  await page.screenshot({ path:path.join(output,'studio-example.png') });
  await page.locator('#workspaceToggle').click();
  await page.goto(origin+'/#/c/long');
  await page.locator('.studio-figure-link').waitFor();
  assert.equal(await page.locator('#studioWorkspace').isVisible(),false,'a loaded diagram respects closed workspace');
  await page.locator('#workspaceOpen').click();
  await page.locator('#studioBoardContent figure[data-kfig] .knarration').waitFor();
  assert.equal(await page.locator('#thread .kboard').count(),0,'original figure moves into workspace');
  const controls = await page.locator('.knarration').boundingBox(), board = await page.locator('.kboard').boundingBox();
  assert.ok(controls.y+controls.height<=board.y,'all narration controls precede drawing');
  await page.getByRole('button',{name:'Play narration',exact:true}).click();
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  assert.equal(await page.evaluate(() => window.activeSpeech),null,'Pause cancels current phrase');
  await page.getByText('Voice & speed',{exact:true}).click();
  await page.getByLabel('Narration speed').selectOption('1.25');
  await page.getByText('Voice & speed',{exact:true}).click();
  await page.locator('.knarration-transcript summary').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('.knarration-transcript').getAttribute('open'),'');
  assert.equal(await page.locator('.knarration-transcript li').count(),3);
  await page.keyboard.press('Enter');
  await page.locator('#studioBoardScroll').evaluate(el => { el.scrollTop=650; });
  const sticky = await page.locator('.knarration').boundingBox(), viewport = await page.locator('#studioBoardScroll').boundingBox();
  assert.ok(Math.abs(sticky.y-viewport.y)<2,'controls remain at top while long board scrolls');
  await page.getByRole('button',{name:'Resume phrase',exact:true}).click();
  await page.getByRole('button',{name:'Pause',exact:true}).waitFor();
  assert.equal(await page.evaluate(() => window.activeSpeech.rate),1.25);
  await page.screenshot({ path:path.join(output,'studio-sticky-controls.png') });
  await page.locator('#workspaceToggle').click();
  assert.equal(await page.evaluate(() => window.activeSpeech),null,'hiding workspace pauses speech');
  assert.ok(await page.locator('#thread').evaluate(el=>el.clientWidth)>1100,'conversation uses available width');
  await page.locator('.studio-figure-link').click();
  assert.equal(await page.evaluate(()=>document.activeElement.id),'studioBoardScroll');
  await page.locator('#newChatBtn').click();
  await page.locator('#studioWelcome').waitFor();
  assert.equal(await page.locator('#studioBoardContent figure').count(),0,'new conversation clears the prior board');
  await page.locator('#input').fill('Keep my table lookup draft.');
  await page.locator('#propertyTablesBtn').click();
  await page.locator('#propertyTableDock').waitFor();
  assert.equal(await page.locator('#studioWorkspace').isVisible(),true,'property tables stay inside the shared workspace');
  assert.equal(await page.locator('#studioBoardScroll').isVisible(),false,'the table tab replaces the drawing within the workspace');
  assert.equal(await page.locator('#studioWorkspace #propertyTableDock').isVisible(),true);
  assert.equal(await page.locator('#input').isVisible(),true,'desktop keeps chat beside tables');
  await page.locator('#closePropertyTables').click();
  assert.equal(await page.locator('#input').inputValue(),'Keep my table lookup draft.');
  assert.equal(await page.locator('#studioWorkspace').isVisible(),true);
  await page.setViewportSize({width:390,height:844});
  await page.goto(origin+'/#/c/long');
  await page.locator('.studio-figure-link').click();
  await page.getByRole('button',{name:'Play narration',exact:true}).click();
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile has no horizontal page overflow');
  const mobileControls=await page.locator('.knarration').boundingBox();
  assert.ok(mobileControls.x>=0 && mobileControls.x+mobileControls.width<=390);
  await page.screenshot({path:path.join(output,'studio-mobile.png')});
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:path.join(output,'studio-dark.png')});
  assert.deepEqual(errors,[]);
  console.log('ok: original logo, practice demo, live figure relocation, top controls, speech pause/resume, keyboard transcript, long-board sticky controls, expanded chat, navigation, mobile, resize and dark mode');
} finally { await browser?.close(); server.closeAllConnections(); await new Promise(resolve=>server.close(resolve)); }
