import assert from 'node:assert/strict';
import { enableLocalDev, localDevEnabled, localDevAvailable, localDevSignIn, localDevUser, localDevSignOut } from '../lib/local-dev-auth.js';
const req = (headers = {}, socket = {}) => ({ headers: { host: '127.0.0.1:3301', origin: 'http://127.0.0.1:3301', 'content-type': 'application/json', ...headers }, socket: { remoteAddress: '127.0.0.1', localPort: 3301, ...socket } });
assert.equal(localDevEnabled(), false);
assert.equal(localDevSignIn(req()), null);
process.env.VERCEL = '1';
assert.throws(enableLocalDev, /local-only/);
delete process.env.VERCEL;
process.env.NODE_ENV = 'production';
assert.throws(enableLocalDev, /local-only/);
process.env.NODE_ENV = 'test';
for (const key of ['DATABASE_URL', 'POSTGRES_URL', 'NEON_AUTH_BASE_URL', 'BLOB_READ_WRITE_TOKEN']) process.env[key] = 'remote-sentinel';
enableLocalDev();
assert.equal(localDevEnabled(), true);
for (const key of ['DATABASE_URL', 'POSTGRES_URL', 'NEON_AUTH_BASE_URL', 'BLOB_READ_WRITE_TOKEN']) assert.equal(process.env[key], undefined);
assert.match(process.env.PGLITE_DIR, /local-dev[\\/]database$/);
assert.equal(localDevUser(req()), null);
for (const request of [req({ origin: 'https://other.example' }), req({ origin: undefined }), req({ host: 'other.example' }), req({ 'x-forwarded-for': '127.0.0.1' }), req({}, { remoteAddress: '192.168.1.4' }), req({ 'content-type': 'text/plain' })]) assert.equal(localDevSignIn(request), null);
const login = localDevSignIn(req());
assert.ok(login.user.id.startsWith('local-dev-'));
assert.match(login.cookie, /HttpOnly; SameSite=Strict/);
const cookie = login.cookie.split(';')[0];
assert.equal(localDevUser(req({ cookie })).id, login.user.id);
assert.equal(localDevUser(req({ cookie: cookie + 'x' })), null);
assert.equal(localDevUser(req({ cookie: 'kelvin_local_dev=' + 'é'.repeat(64) })), null);
assert.equal(localDevSignOut(req({ origin: 'https://other.example' })), null);
assert.ok(localDevSignOut(req()));
assert.equal(localDevUser(req({ cookie })), null);
process.env.VERCEL = '1';
assert.equal(localDevAvailable(req()), false);
assert.equal(localDevUser(req({ cookie })), null);
delete process.env.VERCEL;
process.env.DATABASE_URL = 'remote-sentinel';
assert.equal(localDevAvailable(req()), false);
console.log('ok  local-only activation, isolated services, origin/host/remote guards, opaque session and logout invalidation');
